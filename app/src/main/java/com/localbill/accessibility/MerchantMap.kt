package com.localbill.accessibility

/**
 * 商家名 → 一级支出分类关键词映射。
 * 按顺序匹配，命中的关键词对应的分类名返回给调用方；未命中返回 null，由调用方归入「其他」。
 */
object MerchantMap {

    /** 有序映射：关键词列表 → 分类名 */
    private val RULES = listOf(
        listOf("美团", "饿了么", "瑞幸", "星巴克", "麦当劳", "肯德基", "海底捞", "蜜雪", "茶百道", "沪上阿姨", "塔斯汀", "喜茶", "奈雪", "霸王茶姬") to "餐饮",
        // 「日常」需排在「购物」之前：含"快递"的京东/淘宝物流件会优先命中日常
        listOf("快递", "顺丰", "中通", "圆通", "韵达", "申通", "菜鸟", "驿站", "邮政", "理发", "美发") to "日常",
        listOf("淘宝", "京东", "拼多多", "天猫", "唯品会", "抖音商城", "苏宁", "得物", "山姆", "盒马") to "购物",
        listOf("滴滴", "高德", "地铁", "公交", "加油", "加油站", "中石化", "中石油", "哈啰", "T3出行", "曹操出行") to "交通",
        listOf("水电", "房租", "物业", "燃气", "供电", "水务", "供暖") to "住宿",
        // 「会员租用」需排在「娱乐」之前：视频/音乐平台扣款多为订阅
        listOf("腾讯视频", "爱奇艺", "优酷", "芒果", "网易云音乐", "QQ音乐", "喜马拉雅", "百度网盘", "夸克网盘", "会员") to "会员租用",
        listOf("医院", "药房", "药店", "诊所", "体检", "医保") to "医疗",
        listOf("电影", "游戏", "王者", "原神", "bilibili", "哔哩哔哩", "KTV", "健身") to "娱乐",
        listOf("携程", "飞猪", "去哪儿", "同程", "华住", "亚朵", "如家", "汉庭", "迪士尼") to "旅游",
        listOf("丝芙兰", "屈臣氏", "完美日记", "花西子", "美妆", "化妆品") to "美妆",
        listOf("话费", "流量", "中国移动", "中国联通", "中国电信", "宽带") to "通讯",
        listOf("书店", "培训", "课程", "教育", "当当", "得到") to "学习"
    )

    /** 匹配商家名，返回分类名；未匹配返回 null */
    fun match(merchant: String): String? {
        val m = merchant.trim()
        if (m.isEmpty()) return null
        for ((keywords, category) in RULES) {
            if (keywords.any { m.contains(it) }) return category
        }
        return null
    }
}
